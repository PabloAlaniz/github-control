import type { AppConfig } from '../config';
import { getOctokit } from '../lib/github';

const WORKFLOW_PATH = '.github/workflows/report-coverage.yml';

/**
 * Dispatch coverage computation on a target repo via GitHub Actions.
 *
 * 1. Check if the repo already has a report-coverage workflow
 * 2. If not, create it via the GitHub API
 * 3. Trigger the workflow via workflow_dispatch
 *
 * The workflow will clone the repo, run tests, parse coverage,
 * and POST the results back to our /api/repos/{repo}/coverage endpoint.
 */
export async function dispatchCoverageCompute(env: AppConfig, owner: string, repo: string) {
  const octokit = getOctokit(env);
  const { data: repoData } = await octokit.repos.get({ owner, repo });
  const defaultBranch = repoData.default_branch;

  // Check if workflow already exists
  let workflowExists = false;
  try {
    await octokit.repos.getContent({ owner, repo, path: WORKFLOW_PATH });
    workflowExists = true;
  } catch (e: any) {
    if (e.status !== 404) throw e;
  }

  // Create workflow if missing
  if (!workflowExists) {
    const template = buildWorkflowTemplate();
    await octokit.repos.createOrUpdateFileContents({
      owner,
      repo,
      path: WORKFLOW_PATH,
      message: 'ci: add coverage reporting workflow',
      content: Buffer.from(template).toString('base64'),
      branch: defaultBranch,
    });
    // GitHub needs a moment to register the new workflow file
    await new Promise(r => setTimeout(r, 3000));
  }

  // Dispatch the workflow
  await octokit.actions.createWorkflowDispatch({
    owner,
    repo,
    workflow_id: 'report-coverage.yml',
    ref: defaultBranch,
  });

  return { dispatched: true, workflowCreated: !workflowExists };
}

// ---------------------------------------------------------------------------
// Workflow template — monorepo-aware, multi-stack
// ---------------------------------------------------------------------------

function buildWorkflowTemplate(): string {
  return `# Auto-generated by GitHub Control dashboard
# Reports test coverage back to the dashboard API.
# Supports Node.js and Python, monorepos and simple repos.
#
# Required org/repo config (Settings → Secrets and Variables → Actions):
#   Variable: DASHBOARD_URL      — Dashboard base URL
#   Secret:   COVERAGE_API_TOKEN — Bearer token for the dashboard API

name: Report coverage

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  coverage:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Setup Node
        if: hashFiles('package.json') != ''
        uses: actions/setup-node@v4
        with:
          node-version: 20
          cache: npm

      - name: Setup Python
        if: hashFiles('pyproject.toml', 'setup.py', 'requirements.txt') != ''
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"

      - name: Detect and run coverage
        env:
          DASHBOARD_URL: \${{ vars.DASHBOARD_URL }}
          TOKEN: \${{ secrets.COVERAGE_API_TOKEN }}
          REPO: \${{ github.repository }}
          SHA: \${{ github.sha }}
        run: |
          set -euo pipefail

          report_coverage() {
            local label="\$1" cov="\$2"
            if [ -n "\$cov" ] && [ -n "\${DASHBOARD_URL:-}" ] && [ -n "\${TOKEN:-}" ]; then
              echo "Reporting: \$label = \${cov}%"
              curl -sS --fail-with-body -X POST \\
                -H "Content-Type: application/json" \\
                -H "Authorization: Bearer \$TOKEN" \\
                "\${DASHBOARD_URL}/api/repos/\${REPO}/coverage" \\
                -d "{\\"coverage\\": \$cov, \\"label\\": \\"\$label\\", \\"commit_sha\\": \\"\$SHA\\"}" || true
            fi
          }

          parse_coverage() {
            local dir="\$1"
            if [ -f "\$dir/coverage/coverage-summary.json" ]; then
              jq -r '.total.lines.pct // empty' "\$dir/coverage/coverage-summary.json" 2>/dev/null | xargs printf '%.0f' 2>/dev/null
              return
            fi
            if [ -f "\$dir/coverage.json" ]; then
              jq -r '.totals.percent_covered // empty' "\$dir/coverage.json" 2>/dev/null | xargs printf '%.0f' 2>/dev/null
              return
            fi
          }

          run_node_coverage() {
            local dir="\$1"
            (cd "\$dir" && npm ci --ignore-scripts 2>/dev/null && \\
             (npx vitest run --coverage 2>/dev/null || npx jest --coverage 2>/dev/null || true))
          }

          # Detect monorepo workspaces
          WORKSPACES=""
          if [ -f "package.json" ]; then
            WORKSPACES=\$(node -e "
              const pkg = require('./package.json');
              const ws = pkg.workspaces || [];
              const dirs = Array.isArray(ws) ? ws : (ws.packages || []);
              const result = [];
              for (const pattern of dirs) {
                const base = pattern.replace(/\\\\/?\\\\*+\$/, '');
                try {
                  const entries = require('fs').readdirSync(base, {withFileTypes:true});
                  for (const e of entries) {
                    if (e.isDirectory()) result.push(base + '/' + e.name);
                  }
                } catch {}
              }
              if (result.length > 0) console.log(result.join('\\\\n'));
            " 2>/dev/null || true)
          fi

          if [ -n "\$WORKSPACES" ]; then
            echo "Monorepo detected. Workspaces:"
            echo "\$WORKSPACES"
            echo "\$WORKSPACES" | while IFS= read -r ws; do
              label=\$(basename "\$ws")
              echo "--- Running coverage for: \$label (\$ws) ---"
              if [ -f "\$ws/package.json" ]; then
                run_node_coverage "\$ws"
              fi
              cov=\$(parse_coverage "\$ws")
              report_coverage "\$label" "\$cov"
            done
          else
            echo "Simple repo — running coverage at root"
            if [ -f "package.json" ]; then
              run_node_coverage "."
            elif [ -f "pyproject.toml" ] || [ -f "setup.py" ]; then
              pip install -e ".[test]" 2>/dev/null || pip install -r requirements.txt 2>/dev/null || true
              pytest --cov --cov-report=json 2>/dev/null || true
            fi
            cov=\$(parse_coverage ".")
            report_coverage "default" "\$cov"
          fi
`;
}
